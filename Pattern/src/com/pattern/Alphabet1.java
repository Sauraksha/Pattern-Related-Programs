//D D D
public class Alphabet1 {
	public static void main(String[] args) {
		for(char ch='A';ch<='D';ch++)
		{
		for(int i=1;i<=3;i++)
		{
			

			{
				if(i==1 || i==2||i==3)
				{
				System.out.print(ch+" ");
				}
			}

		}
		System.out.println();
	}
}
}
